#ifndef _FLOW_TEMP_SENSOR_H_
#define _FLOW_TEMP_SENSOR_H_

/*********************************************************************************************************
*                                              包含头文件
*********************************************************************************************************/
#include "stdint.h"

/*********************************************************************************************************
*                                              宏定义
*********************************************************************************************************/

/*********************************************************************************************************
*                                              枚举
*********************************************************************************************************/
typedef enum
{
  //  压力计
  ENUM_I2C_SSC=0,
  ENUM_I2C_ABP,
  
  //  温湿度传感器
  ENUM_I2C_BOARDTEMP,
  ENUM_I2C_BUMPTEMP,
  
  ENUM_I2C_MAX
}EnumCSI2C;

/*********************************************************************************************************
*                                              结构体
*********************************************************************************************************/

/*********************************************************************************************************
*                                              API列表
*********************************************************************************************************/
void InitI2C(void);

void I2C_SetCSFlag(EnumCSI2C I2C_NAME);   // 片选此刻的I2C设备
uint8_t I2C_GetEOC(void);

void I2C_Start(void);                 // I2C开始信号
void I2C_Stop(void);                  // I2C结束信号
void I2C_SendHeader(uint8_t w_or_r);  // 读取/写入数据头
void I2C_WriteByte(uint8_t byte);  // 发送一字节
uint8_t I2C_ReadByte(void);  // 读取一字节
void I2C_SendACK(uint8_t a_or_u);     // 发送ACK/UACK
uint8_t I2C_ReceiveACK(void);         // 读取ACK/UACK
uint8_t I2C_ReadSDA(void);

#endif
