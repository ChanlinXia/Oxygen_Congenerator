void GPIOConfig(void);

/*********************************************************************************************************
*                                              内部函数实现
*********************************************************************************************************/
/*************************************************
*   
*
*   @param  void
*   @return void
*   @author Chanlin
**************************************************/
void GPIOConfig(void)
{
  rcu_periph_clock_enable(RCU_GPIOD);
  
  gpio_init(GPIOD,GPIO_MODE_OUT_PP,GPIO_OSPEED_50MHZ,GPIO_PIN_2);
  gpio_bit_reset(GPIOD,GPIO_PIN_2);
}

/*************************************************
*
*
*   @param  void
*   @return void
*   @author Chanlin
**************************************************/

/*********************************************************************************************************
*                                              API实现
*********************************************************************************************************/
/*************************************************
*
*
*   @param  void
*   @return void
*   @author Chanlin
**************************************************/
void InitBEEPHW(void)
{
  GPIOConfig();
}

/*************************************************
*
*
*   @param  void
*   @return void
*   @author Chanlin
**************************************************/
void BEEPSwitch(unsigned char status)
{
  gpio_bit_write(GPIOD,GPIO_PIN_2,(bit_status)status);
}


