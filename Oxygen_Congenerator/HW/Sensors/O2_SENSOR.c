static unsigned int O2SensorSendByte(unsigned char byte);   //  单字节发送
static unsigned int O2SensorSendBytes(unsigned char* bytes);//  字符串发送

/*********************************************************************************************************
*                                              内部函数实现
*********************************************************************************************************/
/*************************************************
*   
*
*   @param  void
*   @return void
*   @author Chanlin
**************************************************/
static unsigned int O2SensorSendByte(unsigned char byte)
{
  return WriteUART(UART3,&byte,1);
}

/*************************************************
*
*
*   @param  void
*   @return void
*   @author Chanlin
**************************************************/
static unsigned int O2SensorSendBytes(unsigned char* bytes)
{
  int i=0;
  
  while(1){
    if(bytes[i] == '\0'){
      i++;
      break;
    }
    O2SensorSendByte(bytes[i]);
    i++;
  }
  
  return i;
}

