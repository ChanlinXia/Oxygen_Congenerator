/*************************************************
*
*
*   @param  void
*   @return void
*   @author Chanlin
**************************************************/
void InitPWMElement(void)
{
  int i=0;
  
  for(i=0;i<ENUM_PWM_MAX;i++){
    SetPWMDuty(i,0);
  }
//  SetPWMDuty(ENUM_FAN_PWM,0);
}

/*************************************************
*
*
*   @param  void
*   @return void
*   @author Chanlin
**************************************************/
void SetPWMDuty(unsigned char element,double duty)
{
  int pulse = (int)(duty*999);
  s_arrPWMDuty[element]=duty;
  WriteChannelDuty(element,pulse);
}

/*************************************************
*
*
*   @param  void
*   @return void
*   @author Chanlin
**************************************************/
double GetPWMDuty(unsigned char element,double duty)
{
  return s_arrPWMDuty[element];
}
