static void GPIOConfig(void);

/*********************************************************************************************************
*                                              内部函数实现
*********************************************************************************************************/
/*************************************************
*   
*
*   @param  void
*   @return void
*   @author Chanlin
**************************************************/
static void GPIOConfig(void)
{
  uint32_t Pins=0;
  
  rcu_periph_clock_enable(RCU_GPIOA|RCU_GPIOB|RCU_GPIOC|RCU_GPIOD|RCU_AF);   //打开端口时钟
//  gpio_pin_remap_config(GPIO_SWJ_SWDPENABLE_REMAP,ENABLE);    // 重映射恢复PA15 PB3 PB4为IO 
  
  /*PA端口引脚初始化*/
  Pins=GPIO_PIN_11|GPIO_PIN_12|GPIO_PIN_15|GPIO_PIN_8;
  gpio_init(GPIOA,GPIO_MODE_OUT_PP,GPIO_OSPEED_50MHZ,Pins);
  gpio_bit_set(GPIOA,Pins);
  
  /*PB端口引脚初始化*/
  // PB端口输出引脚初始化
  Pins=GPIO_PIN_1|GPIO_PIN_12|GPIO_PIN_14|GPIO_PIN_15|BITS(5,8);
  gpio_init(GPIOB,GPIO_MODE_OUT_PP,GPIO_OSPEED_50MHZ,Pins);
  gpio_bit_set(GPIOA,Pins);
  // PB端口输入引脚初始化
  gpio_init(GPIOB,GPIO_MODE_IPD,GPIO_OSPEED_50MHZ,GPIO_PIN_13|GPIO_PIN_3|GPIO_PIN_4|GPIO_PIN_9);
  
  /*PC端口引脚初始化*/
  Pins=GPIO_PIN_8|GPIO_PIN_9|GPIO_PIN_12|GPIO_PIN_13|BITS(4,6);
  gpio_init(GPIOC,GPIO_MODE_OUT_PP,GPIO_OSPEED_50MHZ,Pins);
  // PC端口输入引脚初始化
  gpio_init(GPIOC,GPIO_MODE_IPD,GPIO_OSPEED_50MHZ,GPIO_PIN_7);
  
  /*PD端口引脚初始化*/
  gpio_init(GPIOD,GPIO_MODE_OUT_PP,GPIO_OSPEED_50MHZ,GPIO_PIN_2);
}


/*********************************************************************************************************
*                                              API实现
*********************************************************************************************************/
/*************************************************
*
*
*   @param  void
*   @return void
*   @author Chanlin
**************************************************/
void InitIOs(void)
{
  GPIOConfig();
}

