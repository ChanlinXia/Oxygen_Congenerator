#define _DATA_BUFFER_H_

typedef short BUFFER_TYPE;

/*********************************************************************************************************
*                                              包含头文件
*********************************************************************************************************/
typedef struct
{
  unsigned short front;       //头索引
  unsigned short currIndex;   //尾索引
  unsigned short len;         //容量长度
  unsigned short currlen;     //实际长度
  
  BUFFER_TYPE maxVal;         //缓冲区的最大值
  BUFFER_TYPE minVal;         //缓冲区的最小值
  
  BUFFER_TYPE* pBuffer;       //缓冲区
}StructDataBuffer;

